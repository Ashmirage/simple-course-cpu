// Assemble only the existing 12 instruction types; no new CPU opcodes.
const fs=require('fs'),path=require('path');const file=path.join(__dirname,'../rtl/program_rom.v');
const old=fs.readFileSync(file,'utf8');
const prefix=[...old.matchAll(/32'd(\d+): inst=32'h([0-9a-f]+);[^\n]*/g)].filter(m=>+m[1]<=324).map(m=>m[0]);
prefix[prefix.findIndex(s=>s.startsWith("32'd304:"))]="32'd304: inst=32'h50001800; // enter interactive initialization";
const p=[],labels={},fix=[];const start=328;
const emit=(w,s)=>p.push({w:w>>>0,s});const label=n=>labels[n]=start+p.length*4;
const addi=(d,j,v)=>emit(0x02800000|((v&4095)<<10)|(j<<5)|d,`addi.w r${d},r${j},${v}`);
const rr=(op,d,j,k)=>emit((op<<15)|(k<<10)|(j<<5)|d,`${op===0x20?'add.w':op===0x22?'sub.w':'and'} r${d},r${j},r${k}`);
const mem=(store,d,j,v)=>emit((store?0x29800000:0x28800000)|((v&4095)<<10)|(j<<5)|d,`${store?'st':'ld'}.w r${d},r${j},${v}`);
const br=(op,j,d,l)=>{fix.push({i:p.length,op,j,d,l});emit(0,`${op} r${j},r${d},${l}`);};
const b=l=>br('b',0,0,l);const copy=(d,j)=>rr(0x20,d,j,0);
// r1 RAM base, r20 MMIO base; r2=2026, r3=7887, r11=8704 survive self-test.
copy(19,1);addi(18,0,256);label('clear');mem(true,0,19,0);addi(19,19,4);addi(18,18,-1);br('bne',18,0,'clear');
copy(23,2);addi(22,0,0);addi(27,0,0);mem(false,26,20,28);
// r30=9999; software clamps arithmetic to decimal display range.
emit(0x14000000|(2<<5)|30,'lu12i.w r30,2');addi(30,30,1807);
label('poll');mem(false,24,20,16);mem(false,16,20,24);
addi(17,0,16);rr(0x29,18,16,17);br('beq',18,0,'no_toggle');
addi(17,0,1);rr(0x22,22,17,22);mem(true,22,20,40);addi(27,0,0);mem(false,26,20,28);
label('no_toggle');br('bne',22,0,'roll');
// Calculate full byte address for selected slot using two adds (slot*4).
rr(0x20,19,24,24);rr(0x20,19,19,19);rr(0x20,19,19,1);
// One action per event snapshot: read > add > subtract > write.
addi(17,0,1);rr(0x29,18,16,17);br('beq',18,0,'try_add');mem(false,23,19,0);b('show_edit');
label('try_add');addi(17,0,2);rr(0x29,18,16,17);br('beq',18,0,'try_sub');
br('beq',23,30,'show_edit');addi(23,23,1);b('show_edit');
label('try_sub');addi(17,0,4);rr(0x29,18,16,17);br('beq',18,0,'try_write');
br('beq',23,0,'show_edit');addi(23,23,-1);b('show_edit');
label('try_write');addi(17,0,8);rr(0x29,18,16,17);br('beq',18,0,'show_edit');mem(true,23,19,0);
label('show_edit');mem(true,23,20,32);
// All eight switches select one of the 256 words; show the decimal slot number.
mem(true,24,20,4);b('poll');
// Roll mode preserves editor and ignores memory/edit keys; S4 still toggles.
label('roll');mem(false,28,20,28);br('beq',28,26,'roll_show');copy(26,28);addi(27,27,1);addi(17,0,3);br('bne',27,17,'roll_show');addi(27,0,0);
label('roll_show');mem(true,0,20,32);br('beq',27,0,'year');addi(17,0,1);br('beq',27,17,'student_b');copy(28,11);b('roll_write');
label('year');copy(28,2);b('roll_write');label('student_b');copy(28,3);
label('roll_write');mem(true,28,20,4);b('poll');
for(const f of fix){const off=(labels[f.l]-(start+f.i*4))/4;p[f.i].w=(f.op==='b'?0x50000000|((off&65535)<<10)|((off>>>16)&1023):(f.op==='beq'?0x58000000:0x5c000000)|((off&65535)<<10)|(f.j<<5)|f.d)>>>0;}
if(start+p.length*4>1024)throw Error('ROM exceeds 256 words');
fs.writeFileSync(file,'// CPU self-test followed by interactive demo. Generated by scripts/generate_demo.cjs.\nmodule program_rom(input wire [31:0] pc,output reg [31:0] inst);\nalways @* case(pc)\n'+prefix.join('\n')+'\n'+p.map((x,i)=>`32'd${start+i*4}: inst=32'h${x.w.toString(16).padStart(8,'0')}; // ${x.s}`).join('\n')+"\ndefault: inst=32'h50000000;\nendcase\nendmodule\n");
console.log(`ROM: ${start/4+p.length}/256 words`);
fs.writeFileSync(file,'`timescale 1ns/1ps\n'+fs.readFileSync(file,'utf8'));
